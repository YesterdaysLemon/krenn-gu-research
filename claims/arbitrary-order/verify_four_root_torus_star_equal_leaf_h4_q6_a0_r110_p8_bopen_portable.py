    if generator_digest != EXPECTED_DIRECT_GENERATOR_DIGEST:
        raise PortableLeafError(f"direct generator digest mismatch: {generator_digest}")
    coefficient_tables = serialize_generators(generators)

    six = base.selector_det(
        algebra, generators, SIX_NAMES, SIX_COLUMNS, "R110 portable six-selector"
    )
    if algebra.is_zero(six):
        raise PortableLeafError("six-selector determinant vanished")
    six_slots = [coefficient_expression(item) for item in six]
    six_numerator = sp.expand(
        sum(
            item.as_numer_denom()[0] * q**index
            for index, item in enumerate(six_slots)
        )
    )
    q6 = base.q6_expression()
    resultant = sp.Poly(sp.resultant(q6, six_numerator, q), p, domain=QQ)
    factor_raw, multiplicity = derive_r110(resultant)
    factor = factor_raw.monic()
    if not sp.Poly(factor_raw.as_expr(), p, modulus=41).is_irreducible:
        raise PortableLeafError("R110 mod-41 irreducibility witness failed")

    gate = sp.Poly(
        p * (p - 1) * (p**2 - p + 1) * (2 * p**2 - 2 * p + 1),
        p,
        domain=QQ,
    )
    gate_degree = int(sp.gcd(factor_raw, gate).degree())
    if gate_degree != 0:
        raise PortableLeafError("R110 meets an excluded coefficient or Delta gate")

    subresultants = sp.subresultants(q6, six_numerator, q)
    linear = next(item for item in subresultants if sp.Poly(item, q).degree() == 1)
    linear_poly = sp.Poly(linear, q, domain=QQ.frac_field(p))
    c0 = p_polynomial(str(linear_poly.coeff_monomial(1))).rem(factor)
    c1 = p_polynomial(str(linear_poly.coeff_monomial(q))).rem(factor)
