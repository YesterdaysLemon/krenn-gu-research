def actual_minor_definitions() -> dict[str, dict[str, list[int]]]:
    definitions = {}
    for name in GENERATOR_ORDER:
        rows, columns = NAMED[name] if name in NAMED else (RSTAR, EXTRA[name])
        definitions[name] = {"rows": list(rows), "columns": list(columns)}
    return definitions


