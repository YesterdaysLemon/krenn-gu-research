    args = parse_args(sys.argv[1:] if argv is None else argv)
    payload, source, runtime = reconstruct()
    rendered_certificate = canonical_json(payload)
    if args.write_certificate:
        CERTIFICATE.parent.mkdir(parents=True, exist_ok=True)
        CERTIFICATE.write_text(rendered_certificate, encoding="utf-8", newline="\n")
        certificate_sha = sha256_bytes(rendered_certificate.encode("utf-8"))
    else:
        certificate_sha = verify_tracked_certificate(payload)
