def canonical_json(payload: dict[str, Any]) -> str:
    return json.dumps(payload, indent=2, sort_keys=True) + "\n"


def verify_tracked_certificate(expected: dict[str, Any]) -> str:
    if not CERTIFICATE.is_file():
        raise PortableLeafError(f"missing tracked certificate: {CERTIFICATE}")
    digest = lf_sha256(CERTIFICATE)
    if digest != EXPECTED_CERTIFICATE_LF_SHA256:
        raise PortableLeafError(f"tracked certificate signature mismatch: {digest}")
    try:
        observed = json.loads(CERTIFICATE.read_text(encoding="utf-8"))
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise PortableLeafError("tracked certificate is not strict UTF-8 JSON") from exc
    if observed != expected:
        raise PortableLeafError("tracked certificate differs from exact reconstruction")
    return digest


def parse_args(argv: Sequence[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--emit-source", type=Path)
    parser.add_argument("--output", type=Path)
    parser.add_argument(
        "--write-certificate",
        action="store_true",
        help="write the deterministic certificate instead of checking its pin",
    )
    return parser.parse_args(argv)


