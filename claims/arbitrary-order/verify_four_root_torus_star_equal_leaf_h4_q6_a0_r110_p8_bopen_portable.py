class PortableLeafError(RuntimeError):
    """Fail-closed source, arithmetic, certificate, or solver-source drift."""


def sha256_bytes(payload: bytes) -> str:
    return hashlib.sha256(payload).hexdigest()


def lf_sha256(path: Path) -> str:
    return sha256_bytes(path.read_bytes().replace(b"\r\n", b"\n"))


def load_base() -> Any:
    if lf_sha256(BASE_VERIFIER) != EXPECTED_BASE_LF_SHA256:
        raise PortableLeafError("pinned GLD101 arithmetic verifier drift")
    spec = importlib.util.spec_from_file_location(
        "gld101_norm_cover_for_r110_portable", BASE_VERIFIER
    )
    if spec is None or spec.loader is None:
        raise PortableLeafError(f"cannot import {BASE_VERIFIER}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def coefficient_expression(value: Any) -> sp.Expr:
    return sp.cancel(sp.sympify(value.as_expr()))


def serialize_generators(generators: dict[str, Any]) -> dict[str, Any]:
    record: dict[str, Any] = {}
    for name in GENERATOR_ORDER:
        record[name] = {
            f"{b_degree},{c_degree}": [
                str(coefficient_expression(item)) for item in coefficient
            ]
            for (b_degree, c_degree), coefficient in sorted(
                generators[name].terms.items()
            )
        }
    return record


def direct_generator_digest(generators: dict[str, Any]) -> str:
    payload: list[Any] = []
    for name in GENERATOR_ORDER:
        terms = []
        for exponent, coefficient in sorted(generators[name].terms.items()):
            slots = []
            for item in coefficient:
                numerator, denominator = coefficient_expression(item).as_numer_denom()
                slots.append([str(numerator), str(denominator)])
            terms.append([list(exponent), slots])
        payload.append([name, terms])
    encoded = json.dumps(payload, separators=(",", ":")).encode("ascii")
    return sha256_bytes(encoded)


def p_polynomial(expression: object) -> sp.Poly:
    return sp.Poly(sp.sympify(expression), p, domain=QQ)


def primitive_integer_polynomial(expression: object) -> sp.Poly:
    polynomial = p_polynomial(expression)
    denominators = [sp.denom(coefficient) for coefficient in polynomial.all_coeffs()]
    scale = sp.ilcm(*[int(value) for value in denominators])
    integer = sp.Poly(sp.expand(scale * polynomial.as_expr()), p, domain=sp.ZZ)
    _content, primitive = integer.primitive()
    if primitive.LC() < 0:
        primitive = -primitive
    return sp.Poly(primitive.as_expr(), p, domain=QQ)


def derive_r110(resultant: sp.Poly) -> tuple[sp.Poly, int]:
    _content, factors = sp.factor_list(resultant.as_expr(), p)
    candidates = []
    for factor, exponent in factors:
        if sp.degree(factor, p) == 110:
            candidates.append((primitive_integer_polynomial(factor), int(exponent)))
    if len(candidates) != 1:
        raise PortableLeafError(f"expected one degree-110 factor, found {len(candidates)}")
    factor, multiplicity = candidates[0]
    factor_hash = sha256_bytes(str(sp.expand(factor.as_expr())).encode("ascii"))
    if factor_hash != EXPECTED_R110_SHA256:
        raise PortableLeafError(f"R110 signature mismatch: {factor_hash}")
    if multiplicity != 1:
        raise PortableLeafError(f"R110 multiplicity drift: {multiplicity}")
    return factor, multiplicity


def reduce_q_polynomial(expression: sp.Expr, factor: sp.Poly) -> sp.Expr:
    result = sp.Integer(0)
    polynomial = sp.Poly(expression, q, domain=QQ.frac_field(p))
    for (q_degree,), coefficient in polynomial.terms():
        reduced = p_polynomial(str(coefficient)).rem(factor)
        result += reduced.as_expr() * q**q_degree
    return sp.expand(result)


def field_multiply(left: sp.Poly, right: sp.Poly, factor: sp.Poly) -> sp.Poly:
    return (left * right).rem(factor)


def field_power(value: sp.Poly, exponent: int, factor: sp.Poly) -> sp.Poly:
    result = sp.Poly(1, p, domain=QQ)
    base = value.rem(factor)
    power = exponent
    while power:
        if power & 1:
            result = field_multiply(result, base, factor)
        power >>= 1
        if power:
            base = field_multiply(base, base, factor)
    return result


def homogeneous_root_evaluation(
    expression: sp.Expr, c0: sp.Poly, c1: sp.Poly, factor: sp.Poly
) -> sp.Poly:
    polynomial = sp.Poly(expression, q, domain=QQ.frac_field(p))
    degree = int(polynomial.degree())
    total = sp.Poly(0, p, domain=QQ)
    for (q_degree,), coefficient in polynomial.terms():
        coefficient_poly = p_polynomial(str(coefficient)).rem(factor)
        term = field_multiply(
            coefficient_poly,
            field_power(-c0, q_degree, factor),
            factor,
        )
        term = field_multiply(
            term,
            field_power(c1, degree - q_degree, factor),
            factor,
        )
        total = (total + term).rem(factor)
    return total


def singular_term(coefficient: Any, exponents: tuple[int, int, int, int]) -> str:
    numerator, denominator = sp.fraction(sp.Rational(coefficient))
    piece = f"({numerator}/{denominator})"
    for variable, exponent in zip(("p", "q", "B", "C"), exponents):
        if exponent:
            piece += "*" + variable
            if exponent != 1:
                piece += f"^{int(exponent)}"
    return piece


def singular_pq(expression: sp.Expr) -> str:
    terms = []
    for (p_degree, q_degree), coefficient in sp.Poly(
        sp.expand(expression), p, q, domain=QQ
    ).terms():
        terms.append(singular_term(coefficient, (p_degree, q_degree, 0, 0)))
    return " + ".join(terms) if terms else "0"


def hard_generator_texts(
    generators: dict[str, Any], factor: sp.Poly
) -> tuple[dict[str, str], dict[str, int]]:
    texts: dict[str, str] = {}
    denominator_gcd_degrees: dict[str, int] = {}
    for name in EIGHT_NAMES:
        slots = [
            coefficient_expression(item)
            for coefficient in generators[name].terms.values()
            for item in coefficient
        ]
        denominator_product = sp.Poly(1, p, domain=QQ)
        for item in slots:
            _numerator, denominator = item.as_numer_denom()
            denominator_product *= p_polynomial(denominator)
        denominator_gcd_degrees[name] = int(
            sp.gcd(denominator_product, factor).degree()
        )
        terms: list[str] = []
        for (b_degree, c_degree), coefficient in sorted(
            generators[name].terms.items()
        ):
            value = sp.Integer(0)
            for q_degree, item in enumerate(coefficient):
                numerator, denominator = coefficient_expression(item).as_numer_denom()
                quotient, remainder = sp.div(
                    denominator_product, p_polynomial(denominator)
                )
                if not remainder.is_zero:
                    raise PortableLeafError(
                        f"{name} coefficient denominator product is not exact"
                    )
                value += (p_polynomial(numerator) * quotient).as_expr() * q**q_degree
            polynomial = sp.Poly(value, q, domain=QQ.frac_field(p))
            for (q_degree,), coefficient in polynomial.terms():
                reduced = p_polynomial(str(coefficient)).rem(factor)
                for (p_degree,), p_coefficient in reduced.terms():
                    terms.append(
                        singular_term(
                            p_coefficient,
                            (p_degree, q_degree, b_degree, c_degree),
                        )
                    )
        texts[name] = " + ".join(terms) if terms else "0"
    if any(degree != 0 for degree in denominator_gcd_degrees.values()):
        raise PortableLeafError("an actual-minor coefficient denominator meets R110")
    return texts, denominator_gcd_degrees


