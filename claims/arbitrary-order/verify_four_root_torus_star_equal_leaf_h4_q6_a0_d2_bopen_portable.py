def render_singular_source(payload: dict[str, Any]) -> str:
    algebra = payload["gaussian_quotient"]
    equations = payload["selected_minor_equations"]
    lines = [
        "// Juniper independent direct-matrix GLD101 d2 B-open audit v1",
        "// p=i; p=-i is coefficientwise conjugate.",
        "// Selected-minor ideal only; no rank converse or global claim.",
        "ring r=(0,i),(q,B,t,z),dp;",
        "minpoly=i^2+1;",
        "option(redSB);",
        f"poly Q6={algebra['q6_p_i']};",
        f"poly Delta={algebra['delta_mod_q6_p_i']};",
    ]
    lines.extend(
        f"poly H_{name}={equations[name]['singular_polynomial']};"
        for name in SELECTORS
    )
    lines.extend(SOURCE_SUFFIX)
    return "\n".join(lines) + "\n"


def check_scope(payload: dict[str, Any]) -> None:
    if payload.get("schema_version") != 1:
        raise PortableD2Error("unsupported certificate schema")
    if payload.get("certificate_id") != (
        "GLD101-A0-D2-B-open-T3-Y1-X3-portable-unit-leaf"
    ):
        raise PortableD2Error("certificate id mismatch")
    if payload.get("status") != "scoped_exact_selected_minor_unit_leaf":
        raise PortableD2Error("certificate status mismatch")
    if payload.get("global_conjecture") != "UNRESOLVED":
        raise PortableD2Error("global status must remain UNRESOLVED")
    scope = payload.get("mathematical_scope", {})
    if scope.get("factor") != "p^2+1=0" or scope.get("normalization") != "a=0":
        raise PortableD2Error("d2/a=0 scope drift")
    if scope.get("open") != "D(B*H2*Delta)":
        raise PortableD2Error("principal-open scope drift")
    if tuple(scope.get("actual_selected_minors", ())) != SELECTORS:
        raise PortableD2Error("six-selector scope drift")
    if tuple(scope.get("compact_unit_core", ())) != COMPACT_CORE:
        raise PortableD2Error("compact selector core drift")
    nonclaims = " ".join(scope.get("nonclaims", ())).lower()
    for phrase in ("no selector converse", "no claim on b=0", "no p8 theorem", "no global"):
        if phrase not in nonclaims:
            raise PortableD2Error(f"missing nonclaim: {phrase}")


def check_arithmetic(payload: dict[str, Any]) -> dict[str, Any]:
    algebra = payload["gaussian_quotient"]
    q6 = parse_singular_polynomial(algebra["q6_p_i"], (q,))
    delta = parse_singular_polynomial(algebra["delta_mod_q6_p_i"], (q,))
    expected_q6 = integral_gaussian_polynomial(
        sp.Poly(q6_expression(sp.I, q), q, extension=sp.I)
    )
    full_delta = sp.Poly(delta_expression(sp.I, q), q, extension=sp.I)
    expected_delta = integral_gaussian_polynomial(full_delta.rem(q6))
    if q6 != expected_q6:
        raise PortableD2Error("Q6 does not match the rational parent at p=i")
    if delta != expected_delta:
        raise PortableD2Error("Delta remainder does not match the rational parent")
    if q6.degree() != 4 or sp.gcd(q6, q6.diff()).degree() != 0:
        raise PortableD2Error("Q6 is not squarefree quartic on p=i")
    if sp.gcd(q6, delta).degree() != 0:
        raise PortableD2Error("Delta is not a unit modulo Q6")
    d2 = sp.Poly(p**2 + 1, p, domain=QQ)
    if not d2.is_irreducible:
        raise PortableD2Error("p^2+1 is not irreducible over QQ")
    h2_at_i = sp.expand(2 * sp.I**2 - 2 * sp.I + 1)
    real, imaginary = h2_at_i.as_real_imag()
    norm = sp.expand(real**2 + imaginary**2)
    if h2_at_i != -1 - 2 * sp.I or norm != 5:
        raise PortableD2Error("H2(i) or its Gaussian norm drifted")
    if algebra.get("h2_p_i") != "-1-2*i" or algebra.get("h2_gaussian_norm") != 5:
        raise PortableD2Error("tracked H2 gate mismatch")

    equations = payload["selected_minor_equations"]
    if set(equations) != set(SELECTORS):
        raise PortableD2Error("equation ordering drift")
    observed = {}
    for name in SELECTORS:
        record = equations[name]
        polynomial = parse_singular_polynomial(
            record["singular_polynomial"], (q, B, t)
        )
        digest = gaussian_polynomial_digest(polynomial)
        if digest != record["scaled_sha256"]:
            raise PortableD2Error(f"{name} scaled equation digest mismatch")
        degrees = {
            "q": int(polynomial.degree(q)),
            "B": int(polynomial.degree(B)),
            "t": int(polynomial.degree(t)),
        }
        if len(polynomial.terms()) != record["terms"] or degrees != record["degrees"]:
            raise PortableD2Error(f"{name} term/degree metadata mismatch")
        observed[name] = {"sha256": digest, "terms": len(polynomial.terms())}
    return {
        "q6_degree": int(q6.degree()),
        "q6_squarefree": True,
        "delta_unit_mod_q6": True,
        "h2_p_i": str(h2_at_i).replace("I", "i").replace(" ", ""),
        "h2_gaussian_norm": int(norm),
        "equations": observed,
    }


def verify(payload: dict[str, Any]) -> dict[str, Any]:
    check_scope(payload)
    arithmetic = check_arithmetic(payload)
    source = render_singular_source(payload)
    source_digest = sha256_bytes(source.encode("utf-8"))
    solver = payload["singular_unit_lift"]
    if source_digest != EXPECTED_SINGULAR_SOURCE_SHA256:
        raise PortableD2Error(f"Singular source digest mismatch: {source_digest}")
    if source_digest != solver.get("source_sha256"):
        raise PortableD2Error("certificate solver-source pin mismatch")
    if len(source.splitlines()) != solver.get("source_line_count"):
        raise PortableD2Error("Singular source line-count mismatch")
    for marker in solver.get("required_terminal_markers", ()):
        if marker not in source:
            raise PortableD2Error(f"missing solver marker: {marker}")
    return {
        "status": "exact_scoped_gld101_d2_bopen_portable_certificate_verified",
        "global_conjecture": "UNRESOLVED",
        "scope": "a=0,p^2+1=0,V(Q6),D(B*H2*Delta),selected necessary minors only",
        "actual_selected_minors": list(SELECTORS),
        "compact_unit_core": list(COMPACT_CORE),
        "p_i_branch": arithmetic,
        "p_minus_i_branch": "coefficientwise conjugate over rational parent equations",
        "singular_source_sha256": source_digest,
        "singular_source_line_count": len(source.splitlines()),
        "certificate_lf_sha256": EXPECTED_CERTIFICATE_LF_SHA256,
        "nonclaims_preserved": True,
    }


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--emit-singular",
        type=Path,
        help="write the deterministic untracked Singular replay source",
    )
    args = parser.parse_args(argv)
    payload = load_certificate()
    report = verify(payload)
    if args.emit_singular is not None:
        target = args.emit_singular.resolve()
        target.parent.mkdir(parents=True, exist_ok=True)
        with target.open("w", encoding="utf-8", newline="\n") as stream:
            stream.write(render_singular_source(payload))
        report["emitted_singular"] = str(target)
    print(json.dumps(report, indent=2, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
