#!/usr/bin/env python3
"""Verify the portable GLD101 d2 B-open compact unit-ideal leaf.

This checker consumes only the tracked JSON certificate.  It validates the
exact six reduced selected-minor equations at p=i, the Q6/Delta and H2 gates,
the coefficientwise-conjugate p=-i branch, and the deterministic Singular
program whose compact ideal is generated by Q6, T3, Y1, X3, and
z*B*Delta-1.  ``--emit-singular`` writes that solver input for a separately
bounded replay; no solver output is trusted or bundled here.

The result is only a selected-necessary-minor leaf on the normalized a=0,
p^2+1=0, B-open chart.  It supplies no selector converse, B=0 or C-open
coverage, endpoint/physical statement, P6/P8 theorem, arbitrary-a result,
full-E31 closure, or global Krenn--Gu resolution.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re
from typing import Any, Sequence

import sympy as sp
from sympy import QQ


ROOT = Path(__file__).resolve().parents[2]
CERTIFICATE = ROOT / "claims" / "arbitrary-order" / "certificates" / (
    "GLD101_A0_D2_BOPEN_T3_Y1_X3_PORTABLE_CERTIFICATE.json"
)

EXPECTED_CERTIFICATE_LF_SHA256 = (
    "e4d0c5a07a930d8c4305a897e613b73185d48df885f9907f0e67a41fc593338c"
)
EXPECTED_SINGULAR_SOURCE_SHA256 = (
    "58530b32e87ff5a4198478c375755ed0452a4c6351ee234872796155c2dd4199"
)
SELECTORS = ("T0", "T1", "T2", "T3", "Y1", "X3")
COMPACT_CORE = ("T3", "Y1", "X3")
q, B, t = sp.symbols("q B t")
p = sp.symbols("p")


class PortableD2Error(RuntimeError):
    """Fail-closed certificate, arithmetic, scope, or source mismatch."""


def sha256_bytes(payload: bytes) -> str:
    return hashlib.sha256(payload).hexdigest()


def lf_sha256(path: Path) -> str:
    return sha256_bytes(path.read_bytes().replace(b"\r\n", b"\n"))


def load_certificate() -> dict[str, Any]:
    digest = lf_sha256(CERTIFICATE)
    if digest != EXPECTED_CERTIFICATE_LF_SHA256:
        raise PortableD2Error(f"certificate LF hash mismatch: {digest}")
    raw = CERTIFICATE.read_bytes().replace(b"\r\n", b"\n")
    payload = json.loads(raw.decode("utf-8"))
    canonical = (json.dumps(payload, indent=2, sort_keys=True) + "\n").encode()
    if raw != canonical:
        raise PortableD2Error("certificate is not canonical sorted JSON")
    return payload


def parse_singular_polynomial(text: str, variables: Sequence[sp.Symbol]) -> sp.Poly:
    python_text = re.sub(r"\bi\b", "I", text.replace("^", "**"))
    expression = sp.sympify(
        python_text,
        locals={"I": sp.I, "q": q, "B": B, "t": t},
    )
    if expression.free_symbols - set(variables):
        raise PortableD2Error(
            f"unexpected symbols in polynomial: {expression.free_symbols}"
        )
    return sp.Poly(sp.expand(expression), *variables, extension=sp.I)


def gaussian_polynomial_digest(polynomial: sp.Poly) -> str:
    encoded = []
    for monomial, coefficient in polynomial.terms():
        real, imaginary = sp.expand(coefficient).as_real_imag()
        real = sp.Rational(real)
        imaginary = sp.Rational(imaginary)
        encoded.append(
            [
                list(monomial),
                int(real.p),
                int(real.q),
                int(imaginary.p),
                int(imaginary.q),
            ]
        )
    return sha256_bytes(json.dumps(encoded, separators=(",", ":")).encode("ascii"))


def integral_gaussian_polynomial(polynomial: sp.Poly) -> sp.Poly:
    """Apply the accepted positive-rational primitive Gaussian scaling."""
    denominator_lcm = 1
    components: list[tuple[sp.Rational, sp.Rational]] = []
    for coefficient in polynomial.coeffs():
        real, imaginary = sp.expand(coefficient).as_real_imag()
        pair = (sp.Rational(real), sp.Rational(imaginary))
        components.append(pair)
        denominator_lcm = sp.ilcm(
            denominator_lcm, int(pair[0].q), int(pair[1].q)
        )
    common = 0
    for value in (
        abs(int(component * denominator_lcm))
        for pair in components
        for component in pair
        if component != 0
    ):
        common = sp.igcd(common, value)
    if common == 0:
        raise PortableD2Error("cannot normalize a zero Gaussian polynomial")
    expression = sp.expand(
        polynomial.as_expr() * sp.Rational(denominator_lcm, common)
    )
    return sp.Poly(expression, *polynomial.gens, extension=sp.I)


def q6_expression(p_value: sp.Expr, q_value: sp.Expr) -> sp.Expr:
    return (
        2 * p_value**4 * q_value**2
        - 2 * p_value**4 * q_value
        + p_value**4
        + 2 * p_value**3 * q_value**3
        - 7 * p_value**3 * q_value**2
        + 5 * p_value**3 * q_value
        - 2 * p_value**3
        + 2 * p_value**2 * q_value**4
        - 7 * p_value**2 * q_value**3
        + 12 * p_value**2 * q_value**2
        - 7 * p_value**2 * q_value
        + 2 * p_value**2
        - 2 * p_value * q_value**4
        + 5 * p_value * q_value**3
        - 7 * p_value * q_value**2
        + 2 * p_value * q_value
        + q_value**4
        - 2 * q_value**3
        + 2 * q_value**2
    )


def delta_expression(p_value: sp.Expr, q_value: sp.Expr) -> sp.Expr:
    return sp.expand(
        (p_value - q_value)
        * (p_value + q_value - 1)
        * (p_value**2 - p_value + 1)
        * (p_value**2 + 2 * p_value * q_value - 2 * p_value - q_value)
        * (2 * p_value * q_value - p_value + q_value**2 - 2 * q_value)
        * (
            2 * p_value * q_value**2
            - 2 * p_value * q_value
            - p_value
            - q_value**2
            - 2 * q_value
            + 2
        )
    )


